/// 按 fight_id 查询楚轩战术提示；未命中返回 None（该场战斗不加提示）。
pub fn chuxuan_tactic(fight_id: &str) -> Option<&'static str> {
    CHUXUAN_TACTICS
        .iter()
        .find(|(k, _)| *k == fight_id)
        .map(|(_, v)| *v)
}

/// 生成一条楚轩提示的战斗日志行（含 `<span class='tactic'>` 样式）。
pub fn chuxuan_tactic_line(fight_id: &str) -> Option<String> {
    chuxuan_tactic(fight_id).map(|t| format!("<span class='tactic'>【楚轩】{t}</span>"))
}
